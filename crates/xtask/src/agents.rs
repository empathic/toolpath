//! The supported-agents list: `docs/agents/support.toml` is the source of truth;
//! `cargo xtask agents` renders `docs/agents/SUPPORT.md` from it, and the tests below fail when an
//! entry disagrees with the repo.

use std::path::Path;

use anyhow::Result;
use serde::Deserialize;

pub const SUPPORT_TOML: &str = "docs/agents/support.toml";
pub const SUPPORT_MD: &str = "docs/agents/SUPPORT.md";

#[derive(Debug, Deserialize)]
pub struct Support {
    #[serde(rename = "agent")]
    pub agents: Vec<Entry>,
}

#[derive(Debug, Deserialize)]
pub struct Entry {
    pub name: String,
    pub vendor: String,
    /// The reader crate, or empty when the agent is documented only.
    #[serde(rename = "crate")]
    pub krate: String,
    pub reader: bool,
    pub writer: bool,
    pub resume: bool,
    /// `green`, `pending` or `none`.
    pub replay: String,
    pub replay_why: String,
    pub live_check: String,
    /// A version present in agents.lock, or `none`.
    pub pinned: String,
    pub format_doc: String,
    pub listed_by: Vec<String>,
}

impl Support {
    pub fn parse(text: &str) -> Result<Support> {
        Ok(toml::from_str(text)?)
    }
}

fn yes(b: bool) -> &'static str {
    if b { "yes" } else { "no" }
}

/// SUPPORT.md, generated: do not edit by hand.
pub fn render(s: &Support) -> String {
    let mut out = String::from(
        "# Supported agents\n\n<!-- generated by `cargo xtask agents` from support.toml; edit that, not this -->\n\n\
         | agent | vendor | crate | reader | writer | resume | replay | live check | pinned | format doc | listed by |\n\
         |---|---|---|---|---|---|---|---|---|---|---|\n",
    );
    for e in &s.agents {
        let replay = if e.replay == "green" {
            "green".to_string()
        } else {
            format!("{}: {}", e.replay, e.replay_why)
        };
        out += &format!(
            "| {} | {} | {} | {} | {} | {} | {} | {} | {} | [{}]({}) | {} |\n",
            e.name,
            e.vendor,
            if e.krate.is_empty() { "-" } else { &e.krate },
            yes(e.reader),
            yes(e.writer),
            yes(e.resume),
            replay.replace('|', "/"),
            e.live_check,
            e.pinned,
            e.format_doc.rsplit('/').next().unwrap_or(&e.format_doc),
            e.format_doc.trim_start_matches("docs/agents/"),
            if e.listed_by.is_empty() {
                "-".to_string()
            } else {
                e.listed_by.join(", ")
            },
        );
    }
    out
}

fn cap(name: &str) -> String {
    let mut c = name.chars();
    c.next()
        .map(|f| f.to_uppercase().collect::<String>() + c.as_str())
        .unwrap_or_default()
}

/// Every way an entry disagrees with the repo under `root` (empty = consistent).
pub fn check(s: &Support, root: &Path) -> Vec<String> {
    let mut bad = Vec::new();
    let read = |rel: &str| std::fs::read_to_string(root.join(rel)).unwrap_or_default();
    let harness = read("crates/path-cli/src/harness.rs");
    let replay_tests = read("crates/toolpath-webmock/tests/replay_agents.rs");
    let lock = read("agents.lock");
    let mut seen: Vec<&str> = Vec::new();
    for e in &s.agents {
        let n = e.name.as_str();
        if seen.contains(&n) {
            bad.push(format!("{n}: listed twice"));
        }
        seen.push(n);
        if !e.krate.is_empty()
            && !root
                .join("crates")
                .join(&e.krate)
                .join("Cargo.toml")
                .is_file()
        {
            bad.push(format!("{n}: crate {} does not exist", e.krate));
        }
        if e.krate.is_empty() && (e.reader || e.writer || e.resume) {
            bad.push(format!("{n}: no crate, yet reader/writer/resume is yes"));
        }
        if e.reader
            && !root
                .join("crates")
                .join(&e.krate)
                .join("src/reader.rs")
                .is_file()
        {
            bad.push(format!(
                "{n}: reader=yes but {}/src/reader.rs is missing",
                e.krate
            ));
        }
        if e.writer
            && !root
                .join(format!("crates/path-cli/src/projection/{n}.rs"))
                .is_file()
        {
            bad.push(format!(
                "{n}: writer=yes but crates/path-cli/src/projection/{n}.rs is missing"
            ));
        }
        if e.resume != harness.contains(&format!("\n    {},", cap(n))) {
            bad.push(format!(
                "{n}: resume={} disagrees with the Harness enum",
                yes(e.resume)
            ));
        }
        match e.replay.as_str() {
            "green" => {
                if !replay_tests.contains(&format!("fn replay_{n}()")) {
                    bad.push(format!(
                        "{n}: replay=green but no replay_{n} test is registered"
                    ));
                }
            }
            "pending" | "none" => {
                if e.replay_why.trim().is_empty() {
                    bad.push(format!("{n}: replay={} needs a replay_why", e.replay));
                }
            }
            other => bad.push(format!(
                "{n}: replay {other:?} is not green, pending or none"
            )),
        }
        if e.pinned != "none" && !lock.contains(&format!("version = \"{}\"", e.pinned)) {
            bad.push(format!("{n}: pinned {} is not in agents.lock", e.pinned));
        }
        if !root.join(&e.format_doc).exists() {
            bad.push(format!("{n}: format doc {} does not exist", e.format_doc));
        }
    }
    bad
}

/// `cargo xtask agents`: render SUPPORT.md next to support.toml.
pub fn run(root: &Path) -> Result<()> {
    let s = Support::parse(&std::fs::read_to_string(root.join(SUPPORT_TOML))?)?;
    let bad = check(&s, root);
    if !bad.is_empty() {
        anyhow::bail!("support.toml disagrees with the repo:\n{}", bad.join("\n"));
    }
    std::fs::write(root.join(SUPPORT_MD), render(&s))?;
    println!("wrote {SUPPORT_MD} ({} agents)", s.agents.len());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn root() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
    }

    fn load() -> Support {
        Support::parse(&std::fs::read_to_string(root().join(SUPPORT_TOML)).unwrap()).unwrap()
    }

    #[test]
    fn the_list_agrees_with_the_repo() {
        let bad = check(&load(), &root());
        assert!(
            bad.is_empty(),
            "support.toml disagrees with the repo:\n{}",
            bad.join("\n")
        );
    }

    #[test]
    fn support_md_is_what_the_list_renders() {
        let want = render(&load());
        let have = std::fs::read_to_string(root().join(SUPPORT_MD)).unwrap_or_default();
        assert_eq!(
            have, want,
            "run `just agents` and commit docs/agents/SUPPORT.md"
        );
    }

    #[test]
    fn today_s_agents_are_all_listed() {
        let names: Vec<String> = load().agents.into_iter().map(|e| e.name).collect();
        for want in [
            "copilot", "claude", "codex", "gemini", "pi", "opencode", "cursor", "agy",
        ] {
            assert!(
                names.iter().any(|n| n == want),
                "{want} missing from support.toml"
            );
        }
    }

    #[test]
    fn a_wrong_entry_is_caught() {
        let s = Support::parse(
            r#"
[[agent]]
name = "ghost"
vendor = "v"
crate = "toolpath-ghost"
reader = true
writer = true
resume = true
replay = "green"
replay_why = ""
live_check = "x"
pinned = "9.9"
format_doc = "docs/agents/formats/nope.md"
listed_by = []
"#,
        )
        .unwrap();
        let bad = check(&s, &root()).join("\n");
        for needle in [
            "crate toolpath-ghost does not exist",
            "reader=yes",
            "writer=yes",
            "Harness enum",
            "replay=green",
            "not in agents.lock",
            "format doc",
        ] {
            assert!(bad.contains(needle), "{needle} not reported in:\n{bad}");
        }
    }
}
